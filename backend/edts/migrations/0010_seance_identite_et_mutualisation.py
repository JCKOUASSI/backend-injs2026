"""PHASE 5 / chantier 1 — identité de séance et mutualisation.

Pourquoi
--------
Une séance n'était identifiable que par le triplet (EDT, créneau, semaine) :
ni date civile, ni statut de cycle de vie, ni rattachement pédagogique propre,
ni identifiant durable pour le QR. La mutualisation, elle, obligeait à
dupliquer la séance par groupe — d'où des présences éclatées sur plusieurs
objets.

Ce que fait cette migration
---------------------------
Huit ajouts **additifs** sur ``edts_affectationcreneau`` — aucun champ
existant n'est supprimé, renommé ni altéré :

* ``annee_academique``, ``semestre``, ``ue``, ``ecue`` — dénormalisation du
  contexte pédagogique déjà porté par ``affectation_pedagogique`` (même motif
  que ``enseignant_nom`` / ``salle_nom``). Alimentation automatique, jamais
  écrasante.
* ``date`` — date civile déduite de ``EmploiDuTemps.rentree`` + numéro de
  semaine + jour du créneau, puis **persistée** pour survivre aux mouvements
  de calendrier.
* ``statut`` — cycle de vie (PLANIFIEE → CONFIRMEE / REPORTEE / ANNULEE /
  REALISEE), distinct de l'activation ``actif`` qui reste la source des
  écrans existants.
* ``jeton_qr`` — identifiant durable et non devinable
  (``secrets.token_urlsafe(32)``), unique. Nécessaire au chaînage
  « EDT → séance → pointage ».
* ``groupes_lies`` (M2M) — groupes **supplémentaires** partageant une même
  séance. Le groupe porteur reste ``groupe`` : il n'y a donc jamais deux
  façons de le désigner, ni duplication de séance.

Points d'attention
------------------
* ``jeton_qr`` est ajouté SANS ``default`` : un défaut appelable sur une
  colonne unique est évalué une seule fois par SQLite et appliqué à toutes
  les lignes, ce qui violerait l'unicité. Les lignes existantes passent à
  NULL, puis ``_remplir_identite_seances`` attribue un jeton distinct à chacune
  AVANT que l'unicité ne soit posée (AlterField final).
* Le calcul de date est recopié dans ``_date_de_seance`` : une migration
  opère sur des modèles historiques, qui n'exposent pas les méthodes du
  modèle courant.

Réversibilité
-------------
``migrate edts 0009`` supprime les huit champs (RemoveField / RemoveField M2M).
Les séances, les pointages et leur rattachement sont **intégralement
conservés** : la migration ne touche à aucune donnée préexistante, elle ne
fait qu'ajouter des colonnes, puis les remplir. Vérifié sur la base de
développement (34 séances, 3 390 pointages).
"""

